#!/usr/bin/env python3
"""Generate the CLI command reference from the Typer app.

Writes docs-mintlify/reference/cli.mdx by introspecting clickwheel's Typer/Click
command tree — so the reference can't drift from the actual commands. Run via
`make docs-reference`; CI ("Docs Reference Freshness") regenerates and fails if
the committed output differs.

Usage: python scripts/gen-cli-reference.py
"""

from __future__ import annotations

import pathlib

import click
import typer.main

from clickwheel.cli import app

OUT = pathlib.Path("docs-mintlify/reference/cli.mdx")

HEADER = """\
---
title: CLI reference
description: Every clickwheel command and option.
---

{/* GENERATED by scripts/gen-cli-reference.py — do not edit by hand. */}

Run `clickwheel --help` (or `clickwheel <command> --help`) for the same
information in your terminal.
"""


def _format_default(param: click.Parameter) -> str:
    if param.default is None or param.default is False:
        return ""
    if param.default is True:
        return "`true`"
    return f"`{param.default}`"


def _params_table(cmd: click.Command, ctx: click.Context) -> list[str]:
    rows: list[str] = []
    for p in cmd.get_params(ctx):
        if p.name == "help":
            continue
        names = ", ".join(f"`{o}`" for o in p.opts)
        kind = "argument" if isinstance(p, click.Argument) else "option"
        help_text = getattr(p, "help", None) or ""
        default = _format_default(p)
        rows.append(f"| {names} | {kind} | {help_text} | {default} |")
    if not rows:
        return []
    return [
        "",
        "| Name | Kind | Description | Default |",
        "| --- | --- | --- | --- |",
        *rows,
    ]


def render() -> str:
    command = typer.main.get_command(app)
    ctx = click.Context(command, info_name="clickwheel")
    lines: list[str] = [HEADER]

    commands: dict[str, click.Command] = getattr(command, "commands", {})
    for name in sorted(commands):
        sub = commands[name]
        if sub.hidden:
            continue
        lines.append(f"\n## `clickwheel {name}`\n")
        help_text = (sub.help or sub.short_help or "").strip()
        if help_text:
            lines.append(help_text + "\n")
        lines.extend(_params_table(sub, ctx))
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
