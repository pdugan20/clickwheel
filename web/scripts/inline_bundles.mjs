#!/usr/bin/env node
/**
 * Build each `web/*.html` entry via Vite's programmatic API and emit
 * `clickwheel/mcp/_ui_bundles.py` with one HTML constant per entry.
 *
 * Why programmatic + Promise.allSettled instead of N `vite build` CLI
 * calls: Vite cold-start is ~5-7s of Node + plugin loading, paid per
 * call. Running everything inside one Node process amortizes that to
 * ~0.5s total. Same output, no plugin surgery — vite-plugin-singlefile
 * is single-input by design and "single Node process running N builds"
 * satisfies that constraint.
 *
 * Output format is a Python module: each bundle becomes
 *   FOO_HTML = "<html string>"
 * plus a UI_BUNDLES dict mapping filename → constant for lookup. Strings
 * are emitted as Python double-quoted literals using a hand-rolled
 * escaper rather than JSON.stringify, because JSON's escape semantics
 * for Unicode line separators differ from Python's source rules.
 *
 * Run via `make build-web` or `cd web && npm run build:bundles`.
 */
import { build } from 'vite';
import react from '@vitejs/plugin-react';
import { viteSingleFile } from 'vite-plugin-singlefile';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

// Script lives in web/scripts/, so up one is web/ and up two is the repo
// root where the Python package lives.
const webDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(webDir, '..');
const distDir = join(webDir, 'dist');
const outFile = join(repoRoot, 'clickwheel', 'mcp', '_ui_bundles.py');

const entries = readdirSync(webDir).filter((name) => {
  if (!name.endsWith('.html')) return false;
  // Skip directories (workbench/) and any aux entries we don't want
  // shipped to the MCP server.
  const full = join(webDir, name);
  return statSync(full).isFile();
});

if (!entries.length) {
  console.error(`No .html entries found in ${webDir}`);
  process.exit(1);
}

const t0 = Date.now();

const results = await Promise.allSettled(
  entries.map((entry) =>
    build({
      root: webDir,
      plugins: [react(), viteSingleFile()],
      logLevel: 'warn',
      build: {
        outDir: distDir,
        emptyOutDir: false,
        rollupOptions: { input: join(webDir, entry) },
      },
    })
  )
);

const failures = results
  .map((r, i) =>
    r.status === 'rejected' ? { entry: entries[i], reason: r.reason } : null
  )
  .filter(Boolean);
if (failures.length) {
  for (const f of failures) {
    console.error(`\n[build:bundles] FAILED ${f.entry}:`);
    console.error(f.reason?.stack ?? f.reason);
  }
  process.exit(1);
}

// U+2028 / U+2029 are valid Python source chars but JavaScript regex
// literals can't hold them without breaking source-level tokenization
// in older Node versions — build via the RegExp constructor with
// hex-escaped patterns so the source file stays plain ASCII.
const RE_LINE_SEP = new RegExp('\\u2028', 'g');
const RE_PARA_SEP = new RegExp('\\u2029', 'g');

function pyDoubleQuoted(s) {
  // Python 3 source files are UTF-8 by default — leave non-ASCII
  // characters inline rather than escaping. Escape only the characters
  // that would break a double-quoted string literal.
  return (
    '"' +
    s
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\n/g, '\\n')
      .replace(/\r/g, '\\r')
      .replace(/\t/g, '\\t')
      .replace(RE_LINE_SEP, '\\u2028')
      .replace(RE_PARA_SEP, '\\u2029') +
    '"'
  );
}

function toConstName(filename) {
  return (
    basename(filename, '.html')
      .toUpperCase()
      .replace(/[^A-Z0-9]+/g, '_')
      .replace(/^_|_$/g, '') + '_HTML'
  );
}

const built = readdirSync(distDir).filter((f) => f.endsWith('.html'));
built.sort();

const lines = [
  '"""Auto-generated by scripts/inline_bundles.mjs — do not edit.',
  '',
  'Re-run `make build-web` to regenerate from `web/*.html` entries.',
  '"""',
  '',
  'from __future__ import annotations',
  '',
];

const manifest = [];
for (const f of built) {
  const html = readFileSync(join(distDir, f), 'utf8');
  const name = toConstName(f);
  lines.push(`${name} = ${pyDoubleQuoted(html)}`);
  lines.push('');
  manifest.push({ file: f, name, size: html.length });
}

lines.push('UI_BUNDLES: dict[str, str] = {');
for (const { file, name } of manifest) {
  lines.push(`    ${pyDoubleQuoted(file)}: ${name},`);
}
lines.push('}');
lines.push('');

writeFileSync(outFile, lines.join('\n'));

const elapsed = ((Date.now() - t0) / 1000).toFixed(2);
console.log(`\nBuilt ${entries.length} entries in ${elapsed}s.`);
console.log(`Wrote ${outFile}:`);
for (const { file, size } of manifest) {
  console.log(`  - ${file}: ${size.toLocaleString()} chars`);
}
